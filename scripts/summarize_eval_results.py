#!/usr/bin/env python3

import argparse
import json
import math
from collections import defaultdict
from pathlib import Path


DIMENSION_KEYS = {
    "benchmark_family",
    "ablation_axis",
    "harness_mode",
    "plan_mode",
    "agent_topology",
    "context_profile.window_bucket",
    "context_profile.ambiguity_level",
    "context_profile.payload_shape",
    "tool_profile.tool_count",
    "tool_profile.return_length",
    "tool_profile.return_shape",
    "tool_profile.implementation_mode",
    "skill_profile.skill_count",
    "skill_profile.skill_style",
    "ambiguity_profile.level",
    "personality_profile.trait",
}


def parse_args():
    parser = argparse.ArgumentParser(description="Summarize Agent Peak Bench eval result JSON.")
    parser.add_argument("result_file", nargs="+", help="One or more result JSON files generated by run_minimax_evals.py")
    parser.add_argument("--json-out", default="", help="Optional path for a machine-readable summary JSON.")
    return parser.parse_args()


def avg(values):
    return round(sum(values) / len(values), 3) if values else 0.0


def percentile(values, q):
    if not values:
        return 0.0
    ordered = sorted(values)
    if len(ordered) == 1:
        return round(float(ordered[0]), 3)
    position = (len(ordered) - 1) * q
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return round(float(ordered[int(position)]), 3)
    lower_value = ordered[lower]
    upper_value = ordered[upper]
    return round(float(lower_value + (upper_value - lower_value) * (position - lower)), 3)


def flatten_metadata(metadata, prefix=""):
    output = {}
    for key, value in (metadata or {}).items():
        name = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            output.update(flatten_metadata(value, name))
        elif isinstance(value, list):
            output[name] = ",".join(str(item) for item in value)
        elif value is not None:
            output[name] = str(value)
    return output


def aggregate_rows(rows):
    pass_rates = [row["pass_rate"] for row in rows]
    eval_scores = [row["avg_evaluation_score"] for row in rows]
    consistency = [row["consistency"] for row in rows]
    latency = [row["avg_latency_ms"] for row in rows]
    p95_latency = [row["p95_latency_ms"] for row in rows if row["p95_latency_ms"]]
    tool_precision = [row["tool_precision_proxy"] for row in rows if row["tool_precision_proxy"] is not None]
    tool_coverage = [row["required_tool_coverage"] for row in rows if row["required_tool_coverage"] is not None]
    json_contract = [row["json_contract_pass_rate"] for row in rows if row["json_contract_pass_rate"] is not None]
    context_chars = [row["generated_context_chars"] for row in rows]
    pass_at_k_values = defaultdict(list)
    for row in rows:
        for key, value in row.get("pass_at_k", {}).items():
            if value is not None:
                pass_at_k_values[key].append(value)
    return {
        "scenario_count": len(rows),
        "avg_pass_rate": avg(pass_rates),
        "avg_evaluation_score": avg(eval_scores),
        "avg_consistency": avg(consistency),
        "avg_latency_ms": avg(latency),
        "p95_latency_ms": percentile(p95_latency or latency, 0.95),
        "avg_tool_precision_proxy": avg(tool_precision) if tool_precision else None,
        "avg_required_tool_coverage": avg(tool_coverage) if tool_coverage else None,
        "avg_json_contract_pass_rate": avg(json_contract) if json_contract else None,
        "avg_generated_context_chars": avg(context_chars),
        "pass_at_k": {key: avg(values) for key, values in sorted(pass_at_k_values.items(), key=lambda item: int(item[0]))},
    }


def main():
    args = parse_args()
    datasets = []
    for result_file in args.result_file:
        path = Path(result_file)
        data = json.loads(path.read_text(encoding="utf-8"))
        datasets.append({"path": str(path), "data": data})

    rows = []
    dimension_rows = defaultdict(list)

    for dataset in datasets:
        data = dataset["data"]
        for suite in data.get("suites", []):
            for result in suite.get("results", []):
                if result.get("skipped"):
                    continue
                category = result.get("category", "unknown")
                summary = result.get("trial_summary", {})
                metadata = result.get("metadata", {})
                row = {
                    "source_result_file": dataset["path"],
                    "id": result.get("id"),
                    "suite": suite.get("suite_name", ""),
                    "category": category,
                    "metadata": metadata,
                    "pass_rate": summary.get("pass_rate", 0.0),
                    "pass_rate_ci95": summary.get("pass_rate_ci95", [0.0, 0.0]),
                    "pass_at_k": summary.get("pass_at_k", {}),
                    "avg_evaluation_score": summary.get("avg_evaluation_score", 0.0),
                    "consistency": summary.get("exact_output_consistency", 0.0),
                    "avg_latency_ms": summary.get("avg_total_latency_ms", 0.0),
                    "p95_latency_ms": summary.get("p95_total_latency_ms", 0.0),
                    "tool_precision_proxy": summary.get("avg_tool_precision_proxy"),
                    "required_tool_coverage": summary.get("avg_required_tool_coverage"),
                    "json_contract_pass_rate": summary.get("json_contract_pass_rate"),
                    "generated_context_chars": summary.get("avg_generated_context_chars", 0.0),
                    "avg_tool_call_count": summary.get("avg_tool_call_count", 0.0),
                }
                rows.append(row)

                dimension_rows["category=" + category].append(row)
                for key, value in flatten_metadata(metadata).items():
                    if key in DIMENSION_KEYS:
                        dimension_rows[f"{key}={value}"].append(row)

    by_dimension = {
        dimension: aggregate_rows(items)
        for dimension, items in sorted(dimension_rows.items())
    }

    print("== Summary ==")
    print(json.dumps({"result_file_count": len(datasets), "scenario_row_count": len(rows)}, ensure_ascii=False, indent=2))
    print("\n== By Dimension ==")
    for dimension, values in by_dimension.items():
        print(json.dumps({"dimension": dimension, **values}, ensure_ascii=False))
    print("\n== By Scenario ==")
    for row in rows:
        print(json.dumps(row, ensure_ascii=False))

    if args.json_out:
        output = {
            "source_result_files": [dataset["path"] for dataset in datasets],
            "summary": {"result_file_count": len(datasets), "scenario_row_count": len(rows)},
            "by_dimension": by_dimension,
            "by_scenario": rows,
        }
        Path(args.json_out).write_text(json.dumps(output, ensure_ascii=False, indent=2), encoding="utf-8")


if __name__ == "__main__":
    main()
