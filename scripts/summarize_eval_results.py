#!/usr/bin/env python3

import argparse
import json
from collections import defaultdict
from pathlib import Path


def parse_args():
    parser = argparse.ArgumentParser(description="Summarize MiniMax eval result JSON.")
    parser.add_argument("result_file", help="Path to a results JSON file generated by run_minimax_evals.py")
    return parser.parse_args()


def avg(values):
    return round(sum(values) / len(values), 3) if values else 0.0


def main():
    args = parse_args()
    data = json.loads(Path(args.result_file).read_text(encoding="utf-8"))

    by_category = defaultdict(lambda: {"pass_rate": [], "consistency": [], "latency": [], "count": 0})
    rows = []

    for suite in data.get("suites", []):
        for result in suite.get("results", []):
            if result.get("skipped"):
                continue
            category = result.get("category", "unknown")
            summary = result.get("trial_summary", {})
            rows.append(
                {
                    "id": result.get("id"),
                    "category": category,
                    "pass_rate": summary.get("pass_rate", 0.0),
                    "pass_at_3": summary.get("pass_at_k", {}).get("3", False),
                    "consistency": summary.get("exact_output_consistency", 0.0),
                    "avg_latency_ms": summary.get("avg_total_latency_ms", 0.0),
                }
            )
            by_category[category]["pass_rate"].append(summary.get("pass_rate", 0.0))
            by_category[category]["consistency"].append(summary.get("exact_output_consistency", 0.0))
            by_category[category]["latency"].append(summary.get("avg_total_latency_ms", 0.0))
            by_category[category]["count"] += 1

    print("== Summary ==")
    print(json.dumps(data.get("summary", {}), ensure_ascii=False, indent=2))
    print("\n== By Category ==")
    for category, values in sorted(by_category.items()):
        print(
            json.dumps(
                {
                    "category": category,
                    "scenario_count": values["count"],
                    "avg_pass_rate": avg(values["pass_rate"]),
                    "avg_consistency": avg(values["consistency"]),
                    "avg_latency_ms": avg(values["latency"]),
                },
                ensure_ascii=False,
            )
        )
    print("\n== By Scenario ==")
    for row in rows:
        print(json.dumps(row, ensure_ascii=False))


if __name__ == "__main__":
    main()
